export function specToPrompt(spec: ProductSpec): string {
  let prompt = `Generate a detailed system architecture for ${spec.name}.\n\n`;
  prompt += `**Description:** ${spec.description}\n\n`;
  prompt += `**Key Features:**\n${spec.features.map(f => `- ${f}`).join("\n")}\n\n`;
  prompt += `**User Stories:**\n${spec.userStories.map(s => `- ${s}`).join("\n")}\n\n`;
  prompt += `**Suggested Tech Stack:** ${spec.techStack.join(", ")}\n\n`;
  prompt += `Design all necessary services, databases, queues, caches, CDNs, and external integrations. Include data flow between components.`;
  return prompt;
}
